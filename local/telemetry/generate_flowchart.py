from __future__ import annotations

"""Auto-generate FLOWCHART.md (Mermaid) from telemetry/*.py using Python's built-in AST."""
""" .venv/bin/python generate_flowchart.py to refresh"""

import ast
import re
import sqlite3
from pathlib import Path

from prometheus_client import CollectorRegistry

from telemetry.db import SCHEMA_SQL
from telemetry.evaluator import FatigueEvaluator
from telemetry.observability import DaemonObservability

PKG_DIR = Path(__file__).parent / "telemetry"
RULES_FILE = Path(__file__).parent / "prometheus_rules.yml"
OUT_FILE = Path(__file__).parent / "FLOWCHART.md"


def extract_prometheus_catalog() -> tuple[list[tuple[str, str]], list[str], list[str]]:
    """Introspect registered Prometheus metrics and prometheus_rules.yml rules."""
    reg = CollectorRegistry()
    DaemonObservability(reg)
    FatigueEvaluator("/tmp/_schema_inspect.db", registry=reg)

    metrics: list[tuple[str, str]] = []
    for collector in reg._collector_to_names:
        for desc in collector.describe():
            metrics.append((desc.name, desc.type))
    metrics.sort()

    rules_text = RULES_FILE.read_text(encoding="utf-8") if RULES_FILE.exists() else ""
    records = re.findall(r"^\s*-\s*record:\s*(\S+)", rules_text, flags=re.MULTILINE)
    alerts = re.findall(r"^\s*-\s*alert:\s*(\S+)", rules_text, flags=re.MULTILINE)
    return metrics, records, alerts


def extract_db_schema() -> dict[str, list[tuple[str, str, bool]]]:
    """Load SCHEMA_SQL into an in-memory SQLite DB and introspect tables/columns."""
    conn = sqlite3.connect(":memory:")
    conn.executescript(SCHEMA_SQL)
    tables = [
        r[0]
        for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' ORDER BY name"
        ).fetchall()
    ]
    schema: dict[str, list[tuple[str, str, bool]]] = {}
    for table in tables:
        cols = conn.execute(f"PRAGMA table_info({table})").fetchall()
        # (name, type, is_pk)
        schema[table] = [(c[1], c[2] or "ANY", bool(c[5])) for c in cols]
    conn.close()
    return schema


def analyze_package(pkg_dir: Path) -> tuple[set[tuple[str, str]], dict[str, list[str]]]:
    """Return (module_edges, module_symbols) parsed from AST."""
    edges: set[tuple[str, str]] = set()
    symbols: dict[str, list[str]] = {}

    for py_file in sorted(pkg_dir.glob("*.py")):
        mod = py_file.stem
        if mod == "__init__":
            continue
        tree = ast.parse(py_file.read_text(encoding="utf-8"))

        # Collect top-level classes and functions
        syms: list[str] = []
        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                syms.append(f"class {node.name}")
            elif isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
                syms.append(f"{node.name}()")
        symbols[mod] = syms

        # Collect internal telemetry.* imports
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module and node.module.startswith("telemetry."):
                target = node.module.split(".")[1]
                if target != mod:
                    edges.add((mod, target))

    return edges, symbols


def build_markdown(edges: set[tuple[str, str]], symbols: dict[str, list[str]]) -> str:
    lines: list[str] = [
        "# Telemetry Architecture & Code Flowchart",
        "",
        "> Auto-generated by `generate_flowchart.py`. Open in VS Code and press **`Cmd+Shift+V`** to preview.",
        "",
        "## 1a. Ingestion & Storage",
        "",
        "```mermaid",
        "flowchart LR",
        '    KS["Keystrokes<br/>hold, flight, backspace"]',
        '    MS["Mouse<br/>75ms moves, clicks"]',
        '    WF["Window Focus<br/>1s poll, >60s idle"]',
        '    WC["Webcam (On-Demand)<br/>60s burst, 20Hz"]',
        '    BW["BatchWriter<br/>5s executemany"]',
        '    RAW[("SQLite WAL<br/>raw_* (14d)")]',
        "",
        "    KS --> BW",
        "    MS --> BW",
        "    WF --> BW",
        "    WC --> BW",
        "    BW --> RAW",
        "```",
        "",
        "## 1b. Evaluation, Anchors, Prometheus & Grafana",
        "",
        "```mermaid",
        "flowchart LR",
        '    RAW[("SQLite WAL<br/>raw_* (14d)")]',
        '    EV["FatigueEvaluator<br/>60s loop, 15m window"]',
        '    PERM[("SQLite Permanent<br/>fatigue_log & app_anchors")]',
        '    WC["Webcam Burst<br/>(10m cooldown)"]',
        '    PROM["Prometheus :9090<br/>Drift, Patterns & Alerts"]',
        '    GF1["Grafana<br/>Fatigue Dashboard"]',
        '    GF2["Grafana<br/>DevOps Health"]',
        "",
        "    RAW --> EV",
        '    EV -->|"log + daily anchors"| PERM',
        '    PERM -->|"zero-cost gauges"| EV',
        '    EV -. "drift / silent" .-> WC',
        '    EV -->|"scrape :9105"| PROM',
        "    PROM --> GF1",
        "    PROM --> GF2",
        "```",
        "",
        "## 2. Module Dependency Graph (Auto-Extracted from AST)",
        "",
        "```mermaid",
        "flowchart LR",
    ]

    for mod, syms in sorted(symbols.items()):
        label = f"{mod}.py"
        if syms:
            label += "<br/>" + "<br/>".join(syms)
        lines.append(f'    {mod}["{label}"]')

    for src, dst in sorted(edges):
        lines.append(f"    {src} --> {dst}")

    lines.extend(
        [
            "```",
            "",
            "## 3. SQLite Database Schema (Auto-Extracted from `SCHEMA_SQL`)",
            "",
            "```mermaid",
            "erDiagram",
        ]
    )

    schema = extract_db_schema()
    for table, cols in schema.items():
        lines.append(f"    {table} {{")
        for col_name, col_type, is_pk in cols:
            pk_tag = " PK" if is_pk else ""
            lines.append(f"        {col_type} {col_name}{pk_tag}")
        lines.append("    }")

    lines.extend(
        [
            '    raw_keystrokes }o--|| app_anchors : "app_hash"',
            '    raw_mouse }o--|| app_anchors : "app_hash"',
            '    raw_windows }o--|| app_anchors : "app_hash"',
            '    raw_webcam }o--o{ fatigue_log : "15m window (ts)"',
            '    fatigue_log }o--|| app_anchors : "app_hash"',
            "```",
            "",
            "## 4. Prometheus Metrics & Rules (Auto-Extracted)",
            "",
            "```mermaid",
            "erDiagram",
        ]
    )

    metrics, records, alerts = extract_prometheus_catalog()
    groups: dict[str, list[tuple[str, str]]] = {
        "PROM_BEHAVIORAL_METRICS": [],
        "PROM_APP_AND_ANCHOR_METRICS": [],
        "PROM_WEBCAM_METRICS": [],
        "PROM_DEVOPS_METRICS": [],
    }
    for name, mtype in metrics:
        if name.startswith(("telemetry_app_", "telemetry_anchor_")):
            groups["PROM_APP_AND_ANCHOR_METRICS"].append((name, mtype))
        elif name.startswith("telemetry_webcam_"):
            groups["PROM_WEBCAM_METRICS"].append((name, mtype))
        elif any(
            k in name
            for k in ("events_", "queue_", "flush_", "eval_", "db_size", "uptime", "errors")
        ):
            groups["PROM_DEVOPS_METRICS"].append((name, mtype))
        else:
            groups["PROM_BEHAVIORAL_METRICS"].append((name, mtype))

    for group_name, items in groups.items():
        lines.append(f"    {group_name} {{")
        for name, mtype in items:
            lines.append(f"        {mtype} {name}")
        lines.append("    }")

    lines.append("    PROM_RECORDING_RULES {")
    for rec in records:
        lines.append(f"        rule {rec.replace(':', '_')}")
    lines.append("    }")

    lines.append("    PROM_ALERTS {")
    for al in alerts:
        lines.append(f"        alert {al}")
    lines.append("    }")

    lines.extend(
        [
            '    PROM_APP_AND_ANCHOR_METRICS ||--o{ PROM_RECORDING_RULES : "per-app drift & patterns"',
            '    PROM_BEHAVIORAL_METRICS ||--o{ PROM_RECORDING_RULES : "focus & switch drift"',
            '    PROM_WEBCAM_METRICS ||--o{ PROM_RECORDING_RULES : "drowsiness"',
            '    PROM_RECORDING_RULES ||--o{ PROM_ALERTS : "triggers"',
            '    PROM_DEVOPS_METRICS ||--o{ GRAFANA_DEVOPS_DASHBOARD : "system health"',
            "```",
            "",
            "## 5. Cluster Alert Decision Tree (IQR-Normalized)",
            "",
            "```mermaid",
            "flowchart LR",
            '    DROWSY["PERCLOS above 0.15 or Microsleeps >= 1 or cluster_sleepiness above 1.5 IQR"] -->|"for 5m"| A_DROWSY["Alert: DrowsinessAlert"]',
            '    MF["cluster_mental_fatigue above 1.5 IQR"] -->|"for 15m"| A_MF["Alert: MentalFatigueAlert"]',
            '    SLOPE["2h fatigue slope above +0.5 IQR/hr and cluster above 0.5"] -->|"for 15m"| A_RAPID["Alert: RapidFatigueBuildupAlert"]',
            '    MORN["Morning 6-11 UTC and cluster_mental_fatigue above 1.2 IQR"] -->|"for 30m"| A_REC["Alert: IncompleteOvernightRecoveryAlert"]',
            '    STRESS["cluster_acute_stress above 1.5 IQR"] -->|"for 30m"| A_STRESS["Alert: SustainedAcuteStressAlert"]',
            "```",
            "",
            "## 6. On-Demand Webcam State Machine",
            "",
            "```mermaid",
            "stateDiagram-v2",
            "    [*] --> CameraOff",
            '    CameraOff --> TriggerCheck : "Every 60s (FatigueEvaluator)"',
            '    TriggerCheck --> CameraOff : "Normal passive data OR idle"',
            '    TriggerCheck --> CooldownCheck : "Passive drift OR silent active work"',
            '    CooldownCheck --> CameraOff : "Within 10m cooldown"',
            '    CooldownCheck --> Burst60s : "Cooldown elapsed"',
            '    Burst60s --> BadFrameFilter : "20Hz frame (in-memory)"',
            '    BadFrameFilter --> Burst60s : "Dim <40 / no face / yaw >0.35 (discarded)"',
            '    BadFrameFilter --> QueueMetrics : "Valid frame (EAR, MAR, pitch, 30s rPPG)"',
            '    QueueMetrics --> Burst60s : "< 60s elapsed"',
            '    Burst60s --> CameraOff : "60s done -> cap.release() (LED off)"',
            "```",
            "",
            "## 7. Runtime Timing Sequence",
            "",
            "```mermaid",
            "sequenceDiagram",
            "    participant C as Collectors (Key/Mouse/Win)",
            "    participant W as BatchWriter",
            "    participant DB as SQLite (WAL)",
            "    participant E as FatigueEvaluator",
            "    participant P as Prometheus (:9090)",
            "    participant G as Grafana (:3000)",
            "",
            "    loop Continuous / 1s Window Poll",
            "        C->>W: enqueue(table, row)",
            "    end",
            "    loop Every 5s",
            "        W->>DB: executemany() flush",
            "    end",
            "    loop Every 60s",
            "        E->>DB: Query 15m sliding window",
            "        E->>DB: Insert fatigue_log (if valid)",
            "        E-->>E: Update :9105/metrics (NaN if gated)",
            "    end",
            "    loop Every 15m (warm-up) / 24h (steady)",
            "        E->>DB: refresh_app_anchors() (>=60 clean rows)",
            "    end",
            "    loop Every 60s",
            "        P->>E: Scrape :9105/metrics",
            "        P-->>P: Evaluate drift, patterns & alerts",
            "    end",
            "    loop Every 30s",
            "        G->>P: Query dashboards",
            "    end",
            "```",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    edges, symbols = analyze_package(PKG_DIR)
    OUT_FILE.write_text(build_markdown(edges, symbols), encoding="utf-8")
    print(f"Generated {OUT_FILE}")


if __name__ == "__main__":
    main()
